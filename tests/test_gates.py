"""The gate that reads a command and the gate that reads text.

The fences read this tree. The identity gate reads the command a hook is about to run,
because who a commit says it is from is not in any file until the commit already exists.
The text gate reads a file, including one that is not in this tree at all, such as the
body of a pull request on its way out.

The tests after those plant a body carrying attribution and expect the gate to refuse it.
The last ones plant a term from a list written here, whole, written across a line break and
written with a space inside it, and expect a refusal each time.
"""

from __future__ import annotations

import importlib.util
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

NOREPLY = "81657828+someone@users.noreply.github.com"
PERSONAL = "someone@example.com"
REFUSED = f"{PERSONAL} is not a GitHub noreply address, and a commit keeps it"

BODY = "Closes #1\n\n## What\n\nOne line of ordinary text.\n"
# Every form of the line a tool appends on its own, from the trailer of a message to the
# footer under a published body. Each one lands on line six of the body below.
APPENDED = (
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "Generated with Claude Code",
    "Generated by [Claude Code](https://claude.ai/code)",
    "_Generated by [Claude Code](https://claude.ai/code)_",
    "https://claude.ai/code/00000000",
    "https://claude.com/claude-code",
)
CARRIES = "carries attribution or a session link"

# A word invented for these tests. The list a real term comes from belongs to a machine,
# and planting one here to prove the gate refuses it would publish the term itself.
PLANTED = "wintermute"
SPLIT_OVER_A_BREAK = "Closes #1\n\nOne winter\nmute of a word.\n"
MATCHES = f"matches the private term {PLANTED}"


def load_gates():
    """The gate script, loaded by path, because scripts is not a package."""
    spec = importlib.util.spec_from_file_location("gates", ROOT / "scripts" / "gates.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


gates = load_gates()


def clone(root: Path, address: str | None = None) -> Path:
    """A repository of its own, so the address under test is the one this test set."""
    subprocess.run(["git", "init", str(root)], check=True, capture_output=True)
    if address is not None:
        subprocess.run(
            ["git", "-C", str(root), "config", "user.email", address],
            check=True,
            capture_output=True,
        )
    return root


def without_git_environment(monkeypatch):
    """The addresses git reads from the environment, taken out of this process."""
    for name in ("GIT_AUTHOR_EMAIL", "GIT_COMMITTER_EMAIL"):
        monkeypatch.delenv(name, raising=False)


def test_the_identity_gate_rejects_an_address_passed_inline(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    command = f"git -c user.name=Someone -c user.email={PERSONAL} commit -m 'a step'"
    assert gates.identity_problems(command, tmp_path) == [REFUSED]


def test_the_identity_gate_accepts_a_noreply_address_passed_inline(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    command = f"git -c user.email={NOREPLY} commit -m 'a step'"
    assert gates.identity_problems(command, tmp_path) == []


def test_the_identity_gate_rejects_an_address_behind_the_author_flag(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    command = f"git -c user.email={NOREPLY} commit --author='A Name <{PERSONAL}>' -m 'a step'"
    assert gates.identity_problems(command, tmp_path) == [REFUSED]


def test_the_identity_gate_rejects_an_address_passed_in_the_environment(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    command = f"GIT_AUTHOR_EMAIL={PERSONAL} GIT_COMMITTER_EMAIL={NOREPLY} git commit -m 'a step'"
    assert gates.identity_problems(command, tmp_path) == [REFUSED]


def test_the_identity_gate_rejects_an_address_already_in_the_environment(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    monkeypatch.setenv("GIT_AUTHOR_EMAIL", PERSONAL)
    monkeypatch.setenv("GIT_COMMITTER_EMAIL", NOREPLY)
    assert gates.identity_problems("git commit -m 'a step'", tmp_path) == [REFUSED]


def test_the_identity_gate_reads_the_address_this_clone_is_configured_with(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    here = clone(tmp_path, PERSONAL)
    assert gates.identity_problems("git commit -m 'a step'", here) == [REFUSED]
    subprocess.run(
        ["git", "-C", str(here), "config", "user.email", NOREPLY],
        check=True,
        capture_output=True,
    )
    assert gates.identity_problems("git commit -m 'a step'", here) == []


def test_the_identity_gate_refuses_a_commit_it_cannot_read_an_address_for(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    monkeypatch.setenv("GIT_CONFIG_GLOBAL", str(tmp_path / "none"))
    monkeypatch.setenv("GIT_CONFIG_SYSTEM", str(tmp_path / "none"))
    here = clone(tmp_path / "work")
    assert gates.identity_problems("git commit -m 'a step'", here) == [
        "this clone has no user.email, so who a commit would be from cannot be read"
    ]


def test_the_identity_gate_covers_every_verb_that_writes_a_commit(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    for verb in ("commit", "merge", "revert", "cherry-pick", "rebase", "am"):
        command = f"git -c user.email={PERSONAL} {verb} HEAD"
        assert gates.identity_problems(command, tmp_path) == [REFUSED], verb


def test_the_identity_gate_leaves_a_push_alone(tmp_path, monkeypatch):
    without_git_environment(monkeypatch)
    assert gates.identity_problems("git push -u origin a-branch", tmp_path) == []


def test_the_text_gate_refuses_attribution_in_a_body_it_is_given(tmp_path):
    """The gate aimed at a published body, over every form of the appended line."""
    body = tmp_path / "body.md"
    for appended in APPENDED:
        body.write_text(BODY + appended + "\n", encoding="utf-8")
        assert gates.check_text([body], [], tmp_path) == [f"body.md:6 {CARRIES}"], appended


def test_the_text_gate_leaves_a_body_nobody_appended_to_alone(tmp_path):
    body = tmp_path / "body.md"
    body.write_text(BODY, encoding="utf-8")
    assert gates.check_text([body], [], tmp_path) == []


def test_the_text_gate_refuses_attribution_in_a_tracked_file(tmp_path):
    """The default run reads every tracked text file, so a body kept as a file is read too."""
    here = clone(tmp_path)
    (here / "notes.md").write_text(BODY + APPENDED[3] + "\n", encoding="utf-8")
    assert gates.check_text([], [], here) == [f"notes.md:6 {CARRIES}"]


def test_the_text_gate_reads_the_docstring_and_the_comment_of_a_python_file(tmp_path):
    planted = tmp_path / "planted.py"
    planted.write_text('"""A module.\n\nGenerated with Claude Code.\n"""\n', encoding="utf-8")
    assert gates.check_text([planted], [], tmp_path) == [f"planted.py:3 {CARRIES}"]
    planted.write_text("# Generated by Claude Code\nVALUE = 1\n", encoding="utf-8")
    assert gates.check_text([planted], [], tmp_path) == [f"planted.py:1 {CARRIES}"]


def test_the_text_gate_holds_these_forms_as_data_in_a_python_file(tmp_path):
    """A string literal is data, which is how the gate and this file carry these forms."""
    planted = tmp_path / "planted.py"
    planted.write_text('MARK = "Generated by Claude Code"\n', encoding="utf-8")
    assert gates.check_text([planted], [], tmp_path) == []
    assert gates.check_text([ROOT / "scripts" / "gates.py"], [], ROOT) == []
    assert gates.check_text([Path(__file__)], [], ROOT) == []


def test_the_text_gate_refuses_attribution_in_the_message_of_a_command():
    refusal = "this message carries attribution, which this repository never uses"
    for appended in APPENDED:
        command = f"git commit -m 'a step' -m '{appended}'"
        assert gates.message_problems(command) == [refusal], appended
    assert gates.message_problems("git commit -m 'a step'") == []


def test_the_text_gate_refuses_a_term_written_across_a_line_break(tmp_path):
    body = tmp_path / "body.md"
    body.write_text(SPLIT_OVER_A_BREAK, encoding="utf-8")
    assert gates.check_text([body], [PLANTED], tmp_path) == [f"body.md:3 {MATCHES}"]


def test_the_text_gate_refuses_a_term_written_with_a_space_inside_it(tmp_path):
    body = tmp_path / "body.md"
    body.write_text("Closes #1\n\nOne winter mute of a word.\n", encoding="utf-8")
    assert gates.check_text([body], [PLANTED], tmp_path) == [f"body.md:3 {MATCHES}"]


def test_the_text_gate_refuses_a_term_of_two_words_across_a_line_break(tmp_path):
    """The view that keeps one space, which is the only one a term of two words survives."""
    body = tmp_path / "body.md"
    body.write_text(SPLIT_OVER_A_BREAK, encoding="utf-8")
    assert gates.check_text([body], ["winter mute"], tmp_path) == [
        "body.md:3 matches the private term winter mute"
    ]


def test_the_text_gate_reports_a_term_once_for_the_line_it_starts_on(tmp_path):
    """Three views of one text, and a term written twice on a line is still one line."""
    body = tmp_path / "body.md"
    body.write_text("One wintermute and one winter\nmute.\n", encoding="utf-8")
    assert gates.check_text([body], [PLANTED], tmp_path) == [f"body.md:1 {MATCHES}"]


def test_the_text_gate_leaves_text_holding_no_term_alone(tmp_path):
    body = tmp_path / "body.md"
    body.write_text(BODY, encoding="utf-8")
    assert gates.check_text([body], [PLANTED], tmp_path) == []


def test_the_text_gate_reads_a_tracked_file_the_way_it_reads_a_file_it_is_given(tmp_path):
    """The default run and a file named on the command line are one route through one check."""
    here = clone(tmp_path)
    planted = here / "notes.md"
    planted.write_text(SPLIT_OVER_A_BREAK, encoding="utf-8")
    assert gates.check_text([], [PLANTED], here) == [f"notes.md:3 {MATCHES}"]
    assert gates.check_text([planted], [PLANTED], here) == [f"notes.md:3 {MATCHES}"]


def test_a_term_arrives_from_a_list_that_is_not_in_this_repository(tmp_path, monkeypatch):
    """The whole route, from a list written for this test to a refusal."""
    listed = tmp_path / "terms.txt"
    listed.write_text(f"# a list written for this test\n\n{PLANTED}\n", encoding="utf-8")
    monkeypatch.setenv("FENCED_TERMS_FILE", str(listed))
    assert gates.load_terms(None) == [PLANTED]
    body = tmp_path / "body.md"
    body.write_text(SPLIT_OVER_A_BREAK, encoding="utf-8")
    assert gates.check_text([body], gates.load_terms(None), tmp_path) == [f"body.md:3 {MATCHES}"]


def test_a_short_term_matches_inside_two_ordinary_words(tmp_path):
    """What reading a term with the whitespace gone costs, planted so it is not a surprise.

    The record is docs/adr/0007-a-private-term-is-read-across-whitespace.md
    """
    body = tmp_path / "body.md"
    body.write_text("Then the person arrived.\n", encoding="utf-8")
    assert gates.check_text([body], ["sonar"], tmp_path) == [
        "body.md:1 matches the private term sonar"
    ]


def test_the_collapsed_views_say_which_line_each_character_came_from(tmp_path):
    for filler in gates.COLLAPSE_TO:
        view, lines = gates.collapsed("ab\n\n  cd\n", filler)
        assert len(view) == len(lines), filler
        assert view.replace(" ", "") == "abcd", filler
        assert lines[0] == 1 and lines[-1] == 3, filler
