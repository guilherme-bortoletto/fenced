"""The one route a pull request body takes out of this repository.

Every test here plants something the publisher has to refuse, and then asks what
reached the wire. A body that breaks a text rule must not be sent at all. A body that
came back changed must not be repaired, because the repair is the second version that
the history of the body keeps for good.

The transport is a fake that records the calls, so nothing in this file reaches GitHub.
"""

from __future__ import annotations

import importlib.util
import urllib.error
import urllib.request
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent

TITLE = "gates: one short title"
BODY = "Closes #1\n\n## What\n\nOne line of ordinary text.\n"
# The forms a publishing tool appends on its own, held here as data the same way the
# gate holds them. Each one is a line nobody typed.
APPENDED = (
    "Generated by [Claude Code](https://claude.ai/code)",
    "_Generated by [Claude Code](https://claude.ai/code)_",
    "Co-authored-by: Claude <noreply@anthropic.com>",
    "https://claude.com/claude-code",
)
CARRIES = "carries attribution or a session link"


def load_publish():
    """The publisher, loaded by path, because scripts is not a package."""
    spec = importlib.util.spec_from_file_location("publish", ROOT / "scripts" / "publish.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


publish = load_publish()


class Fake:
    """A transport that records every call and answers with a body of its choosing."""

    def __init__(self, stored: str | None = None, number: int = 7):
        self.calls = []
        self.stored = stored
        self.number = number

    def __call__(self, method, url, payload, key):
        self.calls.append({"method": method, "url": url, "payload": payload, "key": key})
        if method == "POST":
            self.sent = (payload or {}).get("body")
            return {"number": self.number, "html_url": f"https://github.com/o/r/pull/{self.number}"}
        kept = self.stored if self.stored is not None else self.sent
        return {"number": self.number, "body": kept}


@pytest.fixture(autouse=True)
def a_token(monkeypatch):
    """A token in the environment, so a refusal in a test is about the text and not the key."""
    monkeypatch.setenv("GITHUB_TOKEN", "a-token-that-goes-nowhere")
    monkeypatch.delenv("GH_TOKEN", raising=False)
    monkeypatch.delenv("FENCED_TERMS_FILE", raising=False)


def opened(transport, title=TITLE, body=BODY, terms=()):
    return publish.publish("o", "r", "claude/issue-1", "main", title, body, list(terms), transport)


def test_the_body_that_reaches_the_wire_is_the_body_that_was_written():
    fake = Fake()
    made = opened(fake)
    assert fake.calls[0]["method"] == "POST"
    assert fake.calls[0]["payload"]["body"] == BODY
    assert fake.calls[0]["payload"]["title"] == TITLE
    assert made == {"number": 7, "url": "https://github.com/o/r/pull/7"}


@pytest.mark.parametrize("line", APPENDED)
def test_a_body_carrying_an_appended_line_is_never_sent(line):
    fake = Fake()
    with pytest.raises(publish.Refused) as refused:
        opened(fake, body=f"{BODY}\n{line}\n")
    assert CARRIES in str(refused.value)
    assert fake.calls == []


@pytest.mark.parametrize("line", APPENDED)
def test_a_title_carrying_an_appended_line_is_never_sent(line):
    fake = Fake()
    with pytest.raises(publish.Refused) as refused:
        opened(fake, title=f"{TITLE} {line}")
    assert CARRIES in str(refused.value)
    assert fake.calls == []


def test_a_body_that_breaks_a_text_rule_is_never_sent():
    fake = Fake()
    with pytest.raises(publish.Refused) as refused:
        opened(fake, body="Closes #1\n\nOne clause is here, and the next one follows;\n")
    assert "uses a semicolon" in str(refused.value)
    assert fake.calls == []


def test_a_private_term_in_a_body_is_never_sent():
    fake = Fake()
    with pytest.raises(publish.Refused) as refused:
        opened(fake, body=f"{BODY}\nThe name is Ingot.\n", terms=("ingot",))
    assert "matches the private term" in str(refused.value)
    assert fake.calls == []


@pytest.mark.parametrize("line", APPENDED)
def test_a_stored_body_that_gained_a_line_is_refused_and_left_alone(line):
    fake = Fake(stored=f"{BODY}\n{line}\n")
    with pytest.raises(publish.Refused) as refused:
        opened(fake)
    assert CARRIES in str(refused.value)
    assert [call["method"] for call in fake.calls] == ["POST", "GET"]


def test_a_stored_body_that_disagrees_is_refused_and_left_alone():
    fake = Fake(stored="Closes #1\n")
    with pytest.raises(publish.Refused) as refused:
        opened(fake)
    assert "does not hold the body that was sent" in str(refused.value)
    assert [call["method"] for call in fake.calls] == ["POST", "GET"]


def test_the_line_endings_github_stores_are_not_a_disagreement():
    fake = Fake(stored=BODY.replace("\n", "\r\n"))
    assert opened(fake)["number"] == 7


def test_an_answer_with_no_number_is_refused():
    class Empty(Fake):
        def __call__(self, method, url, payload, key):
            self.calls.append(method)
            return {}

    fake = Empty()
    with pytest.raises(publish.Refused) as refused:
        opened(fake)
    assert "no pull request number" in str(refused.value)
    assert fake.calls == ["POST"]


def test_nothing_is_sent_without_a_token(monkeypatch):
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)
    fake = Fake()
    with pytest.raises(publish.Refused) as refused:
        opened(fake)
    assert "no token in the environment" in str(refused.value)
    assert fake.calls == []


def test_a_refusal_from_github_is_a_refusal_here(monkeypatch):
    def refuse(request, timeout=None):
        raise urllib.error.HTTPError(request.full_url, 422, "Unprocessable", {}, None)

    monkeypatch.setattr(urllib.request, "urlopen", refuse)
    with pytest.raises(publish.Refused) as refused:
        publish.send("POST", "https://api.github.com/repos/o/r/pulls", {"title": "t"}, "k")
    assert "answered 422" in str(refused.value)


def test_a_call_that_does_not_complete_is_a_refusal(monkeypatch):
    def broken(request, timeout=None):
        raise urllib.error.URLError("no route")

    monkeypatch.setattr(urllib.request, "urlopen", broken)
    with pytest.raises(publish.Refused) as refused:
        publish.send("GET", "https://api.github.com/repos/o/r/pulls/1", None, "k")
    assert "did not complete" in str(refused.value)


def test_there_is_no_route_in_here_that_changes_a_body_that_already_exists():
    """The absence is the fence. A body is written once, and an edit records the version before it."""
    source = (ROOT / "scripts" / "publish.py").read_text(encoding="utf-8")
    for method in ("PATCH", "PUT"):
        assert method not in source
